// 種類（MSB << 7 | LSB）から。表に無い LSB なら、同じ MSB の LSB 0 の並び。無ければ nullptr
inline const fx_def *fx_find(int type)
{
	const int msb = type >> 7, lsb = type & 0x7f;
	for (const fx_def &d : FX_DEFS)
		if (d.msb == msb && d.lsb == lsb)
			return &d;
	for (const fx_def &d : FX_DEFS)
		if (d.msb == msb && d.lsb == 0)
			return &d;
	return nullptr;
}

